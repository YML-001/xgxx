def assert_catalog():
    codes = tuple(item[0] for item in TEMPLATES)
    if codes != EXPECTED:
        raise SystemExit("模板编号与约定不一致：%s" % (codes,))
    banned = {"M-12", "M-14", "M-18"}
    hit = banned.intersection(codes)
    if hit:
        raise SystemExit("已停用模板被列入在用：%s" % "、".join(sorted(hit)))
    blob_parts = [
        ROLE_NAMES, NOTE_KEZHANG, CHAIN, RECEIPT_NOTE, LIMIT_NOTE, FLOW_NOTE,
        COLLEGE_NOTE, APPROVAL_NOTE, STATUS_NOTE, REASSIGN_NOTE, WITHDRAW_NOTE,
        SECOND_NOTE, PUBLIC_1, PUBLIC_2, HANDLER, NODE_MAP, CANCELLED,
        CHANNEL_NOTE, PLACEHOLDERS, ACK, DONE,
    ]
    for row in ROLES + FLOW + DROPPED + PLACEHOLDER_ROWS:
        blob_parts.extend(row)
    for row in TEMPLATES:
        blob_parts.extend(row)
    blob = "\n".join(blob_parts)
    bad = [word for word in FORBIDDEN if word in blob]
    if bad:
        raise SystemExit("口径文本含禁用表述：" + "、".join(bad))
    for needle in ("可以同时", "M-25", "指定负责科室", "也不直接分给科室分管领导"):
        if needle not in blob:
            raise SystemExit("口径文本缺少：" + needle)


def assert_docx(path, expect_toc=False):
    from docx import Document

    doc = Document(path)
    if not doc.paragraphs:
        raise SystemExit(path + " 无法打开或没有正文")
    parts = [p.text for p in doc.paragraphs]
    for table in doc.tables:
        for row in table.rows:
            seen = set()
            for cell in row.cells:
                if cell._tc in seen:
                    continue
                seen.add(cell._tc)
                parts.append(cell.text)
    for sec in doc.sections:
        for part in (sec.header, sec.footer, sec.first_page_header, sec.first_page_footer):
            if part is None:
                continue
            for p in part.paragraphs:
                parts.append(p.text or "")
    text = "\n".join(parts)
    bad = [word for word in FORBIDDEN if word in text]
    if bad:
        raise SystemExit(path + " 含禁用表述：" + "、".join(bad))
    required = (
        "M-25", "指定负责科室", "科室回复人", "科室分管领导", "可以同时",
        "全部公开", "仅该学院副书记可见", "M-12", "M-14", "M-18",
        "也不直接分给科室分管领导", "回复稿已返回",
    )
    missing = [word for word in required if word not in text]
    if missing:
        raise SystemExit(path + " 缺少口径：" + "、".join(missing))
    for code in EXPECTED:
        if code not in text:
            raise SystemExit(path + " 缺少在用模板 " + code)
    if expect_toc and "TOC" not in doc.element.xml:
        raise SystemExit(path + " 缺少可更新的目录域")
    return doc
