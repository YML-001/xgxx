#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成《学工信箱修改清单》Word，含业务流程图和学生消息模板。"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from docx.shared import Cm, Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx_kit import Builder, set_run, FONT_HEAD

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "学工信箱修改清单.docx")
FLOW = os.path.join(ROOT, "docs", "manual-assets", "mailbox-flow.png")

ACK = (
    "尊敬的{姓名}同学：\n"
    "您好！您于{来信时间}通过学工信箱提交的来信「{标题}」（编号{编号}）我们已经收到，感谢您的反馈。\n"
    "综合办公室将进行受理，并流转至相关科室办理。我们将在7天内给予您正式回复，请留意「我的信件」中的办理进度。\n"
    "本消息仅表示来信已收悉，正式办理结果将另行答复。\n"
    "学工部综合办公室\n"
    "{回执时间}"
)

DONE = (
    "尊敬的{姓名}同学：\n"
    "您提交的来信「{标题}」（编号{编号}）已办理完成。请登录学工信箱，在「我的信件」中查看正式答复。\n"
    "学工部综合办公室\n"
    "{答复时间}"
)


def lines(b, text):
    for line in text.split("\n"):
        b.body(line, indent=False)


def figure(b, path, caption):
    p = b.doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.add_run().add_picture(path, width=Cm(16))
    cap = b.doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_before = Pt(2)
    cap.paragraph_format.space_after = Pt(8)
    set_run(cap.add_run(caption), FONT_HEAD, 10.5, bold=True)


def main():
    b = Builder()
    b.h("学工信箱修改方案", 1)
    b.note("2026年10月　·　以下口径均已确认。科室科长就是科室领导，分案和审批由同一人完成。")
    b.body("在现有「学生提交 → 综合办派发 → 科室答复办结」上调整分案、审定、学院协同和公开范围。系统不再按问题类型自动推荐科室。学生提交后先收到 7 天回执；正式答复必须经过科室领导审批，并由回复人确认后才发给学生。")

    b.h("一、已确认的调整", 1)
    b.table(
        ["序号", "事项", "确认口径"],
        [
            ["1", "回执时长", "学生收到的回执写明 7 天内给予正式回复。"],
            ["2", "审批范围", "所有信件都要科室领导审批，简单回复也不例外。"],
            ["3", "审批之后", "领导通过后不直接发给学生，由回复人再确认后发送。"],
            ["4", "审批不通过", "打回回复人。回复人按修改意见编辑后，再交领导审批，通过后再回复。"],
            ["5", "学院协同", "回复人不能直接拟写时，学院协同直接交给学院副书记，不再经过学办主任。副书记指定人员线下承办，承办结果回到副书记；由副书记写处理意见后发回回复人编辑，再交科室领导审批。线下承办不作为系统审批环节。"],
            ["6", "公开范围", "科室选择：全部公开，或仅该学院副书记可见。"],
            ["7", "分案方式", "综合办先分给科室领导（科长），再由其指定具体回复人。分案和审批是同一人。"],
            ["8", "取消推荐", "不做按问题类型自动推荐科室。"],
        ],
        [1.6, 3.0, 11.4],
        font=10.5,
        aligns=["center", "center", "left"],
    )

    b.h("二、完整业务流程", 1)
    b.body("主流程在左侧。回复人不能直接拟写时走右侧学院协同，结束后回到「回复人编辑答复」。科室领导不通过时走右侧打回，修改后重新审批。")
    figure(b, FLOW, "图 1  学工信箱办理流程")
    b.bullet("学生提交后，系统立刻发送统一回执。回执只表示已收到，状态仍是待分派，不算办结。")
    b.bullet("综合办只指定科室领导（科长），不直接指定回复人，也不按事务类型给出建议科室。")
    b.bullet("科室领导指定回复人。回复人能写的，直接编辑答复；不能写的，直接交给学生所在学院的副书记，不再经过学办主任。")
    b.bullet("副书记指定人员线下承办，承办结果回到副书记。副书记写处理意见后发回科室回复人，由回复人编辑进正式答复。线下承办不作为系统审批环节。")
    b.bullet("所有正式答复都提交科室领导审批。不通过则打回回复人，按意见修改后再次审批，通过前学生看不到答复正文。")
    b.bullet("领导通过后，回复人再确认一次，系统才把正式答复发给学生并办结。")
    b.bullet("办结时或办结后，科室选择公开范围：全部公开，或只给该学院副书记看。给学生本人的正式答复不受这个范围影响。")

    b.h("三、学生消息模板", 1)
    b.h("3.1 提交回执（提交成功后立即发送）", 2)
    b.body("时长固定写「7天」。只存草稿不发送。系统消息和 ITS 使用同一正文。")
    b.caption("模板正文")
    lines(b, ACK)
    b.h("3.2 正式答复提醒（回复人确认发送后）", 2)
    b.body("这封才表示办理完成。与上面的收悉回执分开，避免学生把回执当成正式结果。")
    b.caption("模板正文")
    lines(b, DONE)
    b.caption("占位符")
    b.table(
        ["占位符", "替换内容"],
        [
            ["{姓名}", "来信学生姓名"],
            ["{来信时间}", "提交时间"],
            ["{标题}", "来信标题"],
            ["{编号}", "信件编号"],
            ["{回执时间}", "回执发出时间"],
            ["{答复时间}", "正式答复发出时间"],
        ],
        [4.5, 11.5],
        font=10.5,
        aligns=["center", "left"],
    )

    b.h("四、相对现行系统要改的功能", 1)
    b.bullet("取消按问题类型自动推荐科室，以及派发时的建议归口、对口成员提示。综合办手工选择科室领导（科长）。")
    b.bullet("综合办派发从「直接选承办人」改为「先选科室领导」。科室领导收到后，再指定具体回复人，并负责审批答复。")
    b.bullet("新增环节：待科室领导分案、副书记接收学院协同并写处理意见、科室领导审批、待回复人确认。分案和审批为同一角色。线下承办不作为系统环节，不再经过学办主任。")
    b.bullet("科室领导审批覆盖全部信件。不通过必须打回回复人，领导不直接改稿发送。")
    b.bullet("审批通过后增加回复人确认。未确认前不对学生展示正式答复，也不办结。")
    b.bullet("回复人可发起学院协同：直接交给学院副书记。副书记指定人员线下承办，写处理意见后回到回复人。")
    b.bullet("科室可为信件或过程信息选择公开范围：全部公开，或仅该学院副书记可见。")
    b.bullet("回执模板中的回复时限写为 7 天，与「超过多少天未办结视为超期」仍分开保存，当前取值都是 7 天。")

    b.h("五、本次不改的内容", 1)
    b.bullet("登录入口不变：PC 端仍从中南大学官网「学生天地」进入智慧学工，移动端仍从「中南大学智慧学工」小程序进入。")
    b.bullet("学生写信字段不改。收悉回执不是满意度评价，也不是二次办理的起点。")

    b.save(OUT)


if __name__ == "__main__":
    main()
