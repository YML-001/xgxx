# ------------------------------------------------------------------ 汇总计算

def compute():
    mod_rows, role_acc, dev_total = [], {}, 0.0
    for code, name, _desc, feats in MODULES:
        sub = sum(f[6] for f in feats)
        dev_total += sub
        mod_rows.append((f"{code}. {name}", len(feats), sub))
        for f in feats:
            role_acc.setdefault(f[2], [0, 0.0])
            role_acc[f[2]][0] += 1
            role_acc[f[2]][1] += f[6]
    impl_total = sum(r[6] for r in IMPLEMENT)
    return mod_rows, role_acc, dev_total, impl_total


def num(x):
    return f"{x:g}"


