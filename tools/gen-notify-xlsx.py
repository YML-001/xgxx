def style_sheet(ws, headers, rows, widths, wrap_cols, row_height=118):
    navy = PatternFill("solid", fgColor="006DAD")
    zebra = PatternFill("solid", fgColor="F4F8FB")
    header_font = Font(name="微软雅黑", size=11, bold=True, color="FFFFFF")
    body_font = Font(name="微软雅黑", size=10, color="1A1A1A")
    thin = Border(
        left=Side(style="thin", color="D0D7DE"),
        right=Side(style="thin", color="D0D7DE"),
        top=Side(style="thin", color="D0D7DE"),
        bottom=Side(style="thin", color="D0D7DE"),
    )
    center = Alignment(horizontal="center", vertical="center", wrap_text=True)
    left = Alignment(horizontal="left", vertical="top", wrap_text=True)

    ws.append(headers)
    for cell in ws[1]:
        cell.fill = navy
        cell.font = header_font
        cell.alignment = center
        cell.border = thin
    ws.row_dimensions[1].height = 28
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows) + 1}"

    for i, row in enumerate(rows, start=2):
        ws.append(list(row))
        ws.row_dimensions[i].height = row_height
        for j, cell in enumerate(ws[i], start=1):
            cell.font = body_font
            cell.border = thin
            cell.alignment = left if j in wrap_cols else center
            if i % 2 == 0:
                cell.fill = zebra

    for idx, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(idx)].width = width

    ws.sheet_view.showGridLines = False
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.page_setup.paperSize = ws.PAPERSIZE_A3
    ws.oddHeader.center.text = "学工信箱 · 消息提醒配置表"
    ws.print_title_rows = "1:1"


